# G-08 共有物の使用・負担・分割（裁判による分割まで）。決め方（保存・管理・変更）と持分は G-04。
from fractions import Fraction as F


def fr(x):
    x = F(x)
    return '%d分の%d' % (x.denominator, x.numerator) if x.denominator != 1 else str(x.numerator)


def yen(n):
    return '{:,}円'.format(int(n))


# 計算例：甲2分の1・乙3分の1・丙6分の1で共有する建物の修繕費90万円。
COST = 900000
SH = {'甲': F(1, 2), '乙': F(1, 3), '丙': F(1, 6)}
PAY = {k: COST * v for k, v in SH.items()}


def verify():
    assert sum(SH.values()) == 1
    assert PAY == {'甲': 450000, '乙': 300000, '丙': 150000}
    assert sum(PAY.values()) == COST


