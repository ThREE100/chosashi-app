# G-04 共有（持分と共有物の管理）
from fractions import Fraction as F


def fr(x):
    x = F(x)
    return '%d分の%d' % (x.denominator, x.numerator) if x.denominator != 1 else str(x.numerator)


# 例：甲・乙・丙が3分の1ずつ共有。甲と乙が賛成。
SHARE = F(1, 3)
AYE = SHARE * 2


def verify():
    assert SHARE * 3 == 1
    assert AYE > F(1, 2)          # 過半数（民法第252条第1項）
    assert SHARE < F(1, 2)        # 1人では過半数にならない


