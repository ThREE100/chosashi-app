# A-02 地積の端数処理と公差
from decimal import Decimal, ROUND_DOWN


def kirisute(area, chimoku):
    """規則第100条：宅地・鉱泉地は0.01未満切捨て。それ以外は10㎡を超えれば1未満切捨て、10㎡以下は0.01未満切捨て。"""
    a = Decimal(str(area))
    if chimoku in ('宅地', '鉱泉地') or a <= 10:
        return a.quantize(Decimal('0.01'), rounding=ROUND_DOWN)
    return a.quantize(Decimal('1'), rounding=ROUND_DOWN)


EX = [(253.60735, '宅地'), (244.789, '雑種地'), (9.876, '雑種地'), (10.995, '畑')]
RES = [kirisute(a, c) for a, c in EX]

# 分筆前後の差（数値は説明用）
BEFORE = Decimal('300.00')
AFTER = [kirisute(146.628, '宅地'), kirisute(153.229, '宅地')]
DIFF = BEFORE - sum(AFTER)


def verify():
    assert RES == [Decimal('253.60'), Decimal('244'), Decimal('9.87'), Decimal('10')]
    assert AFTER == [Decimal('146.62'), Decimal('153.22')]
    assert DIFF == Decimal('0.16')


