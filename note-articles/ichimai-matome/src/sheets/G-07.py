# G-07 相続の承認と放棄（熟慮期間と単純承認）。相続人・相続分は G-03。
import datetime as dt

# 計算例：自己のために相続の開始があったことを知った日が4月10日。
KNEW = dt.date(2026, 4, 10)
START = KNEW + dt.timedelta(days=1)          # 初日不算入（民法第140条）
OUJI = dt.date(START.year, START.month + 3, START.day)   # 3か月後の起算日に応当する日
END = OUJI - dt.timedelta(days=1)            # その前日に満了（民法第143条第2項）


def md(d):
    return '%d月%d日' % (d.month, d.day)


def verify():
    assert START == dt.date(2026, 4, 11)
    assert OUJI == dt.date(2026, 7, 11)
    assert END == dt.date(2026, 7, 10)


