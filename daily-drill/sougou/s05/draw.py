_sp.loader.exec_module(_m)
_P, _, _OUT = chain.solve_a(chain.design(copy.deepcopy(_m.SPEC)))
P = {k: (round(_P[k].real, 2), round(_P[k].imag, 2)) for k in 'ABCDEF'}
T = {k: (_P[k].real, _P[k].imag) for k in ('T1', 'T2')}

SIDES = [('A', 'E'), ('E', 'B'), ('B', 'C'), ('C', 'F'), ('F', 'D'), ('D', 'A'), ('E', 'F')]
LEN = {}
for a, b in SIDES:
    v = math.hypot(P[a][0] - P[b][0], P[a][1] - P[b][1])
    assert abs((v * 100) % 1 - 0.5) > 0.07, (a, b, v)       # 四捨五入の境目を避ける
    LEN[a + b] = round(v + 1e-12, 2)
assert LEN['EF'] == _OUT['辺EFの長さ'], LEN
AI, RO = _OUT['ai'], _OUT['ro']
assert (AI, RO) == (204.62, 36.00)
