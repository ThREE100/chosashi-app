_sp = importlib.util.spec_from_file_location('s01_calc_for_draw', os.path.join(HERE, 'calc.py'))
_m = importlib.util.module_from_spec(_sp)
_sp.loader.exec_module(_m)
_P, _, _OUT = chain.solve_a(chain.design(copy.deepcopy(_m.SPEC)))
P = {k: (round(_P[k].real, 2), round(_P[k].imag, 2)) for k in 'ABCDEF'}
T = {k: (_P[k].real, _P[k].imag) for k in ('T1', 'T2')}

SIDES = [('A', 'B'), ('B', 'F'), ('F', 'C'), ('C', 'D'), ('D', 'E'), ('E', 'A'), ('E', 'F')]
LEN = {}
for a, b in SIDES:
    v = math.hypot(P[a][0] - P[b][0], P[a][1] - P[b][1])
    assert abs((v * 100) % 1 - 0.5) > 0.07, (a, b, v)       # 四捨五入の境目を避ける
    LEN[a + b] = round(v + 1e-12, 2)
assert LEN['EF'] == _OUT['辺EFの長さ'] == 22.64, LEN
AI, RO = _OUT['ai'], _OUT['ro']
assert (AI, RO) == (214.81, 323.86)
MARK = {'A': '金属標', 'B': '金属標', 'C': 'コンクリート杭', 'D': 'コンクリート杭', 'E': '金属標', 'F': '金属標'}

import calc_keys as _ck  # noqa: E402
_d = _ck.Doc()
for a, b in SIDES:
    _d.add(f'辺{a}{b}', f'Abs({b} − {a})', f'[Abs] {P[b][0]:g} [+] {P[b][1]:g} [i] [−] [(] {P[a][0]:g} [+] {P[a][1]:g} [i] [)] [)] [=]')
_KEYS = [{'title': s_['title'], 'formula': s_['formula'], 'keys': s_['keys'], 'display': s_['display']} for s_ in _d.run()]
for (a, b), s_ in zip(SIDES, _KEYS):
    assert round(_ck.val(s_) + 1e-9, 2) == LEN[a + b], (a, b, s_['display'])

