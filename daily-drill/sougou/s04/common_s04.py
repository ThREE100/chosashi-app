"""s04（建物）の事案の共通データ。calc.py・form.py・draw.py が同じ座標・寸法から計算する（値を手で写さない）。
座標は X＝北・Y＝東（m）。建物の点は壁の中心線の交点（壁の厚さ0.14 → 中心線から外壁の面まで0.07）。
事案：山川一郎が所有権の登記名義人の甲建物（5番の土地の上、平家建、抵当権あり）と乙建物（6番の土地の上、2階建）の間を
増築でつなぎ、障壁を取り除いて構造上1個の居宅にした（所有権の登記がある2個の建物の合体。法第49条第1項第5号）。"""
import math

ADDR = 'A市C町二丁目'
OWNER_ADDR = 'A市C町二丁目5番1号'
OWNER = '山川一郎'
SON = '山川健太'
FATHER = '山川一男'

# 本件土地：5番（西）＝A・B・E・F、6番（東）＝B・C・D・E。筆界B-Eは南北の直線（Y＝316.00）
SITE = {'A': (515.00, 300.00), 'B': (515.00, 316.00), 'C': (515.00, 334.00),
        'D': (500.00, 334.00), 'E': (500.00, 316.00), 'F': (500.00, 300.00)}
LOT5 = ['A', 'B', 'E', 'F']
LOT6 = ['B', 'C', 'D', 'E']
YB = SITE['B'][1]          # 5番と6番の筆界の Y 座標

# 甲建物（家屋番号5番、平家建）：東西10.92×南北8.19
K = {'k1': (511.19, 302.00), 'k2': (511.19, 312.92), 'k3': (503.00, 312.92), 'k4': (503.00, 302.00)}
# 乙建物（家屋番号6番、2階建）：1階 東西10.01×南北9.10、2階 西側の東西7.28×南北9.10
O = {'o1': (512.10, 321.64), 'o2': (512.10, 331.65), 'o3': (503.00, 331.65), 'o4': (503.00, 321.64),
     'o5': (512.10, 328.92), 'o6': (503.00, 328.92)}
# 増築部分（平家建）：甲建物の東の壁と乙建物の西の壁の間。南の壁は甲・乙の南の壁と一直線（X＝503.00）、北の壁は z1・z2
Z = {'z1': (507.55, 312.92), 'z2': (507.55, 321.64)}
HALF = 0.07

P = {**SITE, **K, **O, **Z}
KOU = [K[k] for k in ('k1', 'k2', 'k3', 'k4')]
OTSU1 = [O[k] for k in ('o1', 'o2', 'o3', 'o4')]
OTSU2 = [O[k] for k in ('o1', 'o5', 'o6', 'o4')]
ZOU = [Z['z1'], Z['z2'], O['o4'], K['k3']]
UNI_N = ['k4', 'k1', 'k2', 'z1', 'z2', 'o1', 'o2', 'o3']           # 工事後の1階の外形（南の辺 o3→k4 は一直線）
UNI = [P[k] for k in UNI_N]
# 筆界B-Eで1階を切った部分
PART5 = [K['k4'], K['k1'], K['k2'], Z['z1'], (Z['z1'][0], YB), (K['k3'][0], YB)]
PART6 = [(Z['z1'][0], YB), Z['z2'], O['o1'], O['o2'], O['o3'], (K['k3'][0], YB)]


def area(pts):
    s = 0.0
    for i in range(len(pts)):
        x0, y0 = pts[i]
        x1, y1 = pts[(i + 1) % len(pts)]
        s += x0 * y1 - x1 * y0
    return abs(s) / 2


def floor2(v):
    return math.floor(v * 100 + 1e-7) / 100


A_KOU, A_OTSU1, A_OTSU2, A_ZOU = (floor2(area(x)) for x in (KOU, OTSU1, OTSU2, ZOU))
A_UNI1, A_UNI2 = floor2(area(UNI)), A_OTSU2
A_P5, A_P6 = floor2(area(PART5)), floor2(area(PART6))
assert (A_KOU, A_OTSU1, A_OTSU2, A_ZOU) == (89.43, 91.09, 66.24, 39.67), (A_KOU, A_OTSU1, A_OTSU2, A_ZOU)
assert A_UNI1 == 220.20 and round(A_KOU + A_ZOU + A_OTSU1, 2) == 220.19      # 部分ごとに切り捨ててから足すと 0.01 少ない
assert (A_P5, A_P6) == (103.44, 116.75) and abs(area(PART5) + area(PART6) - area(UNI)) < 1e-9
LOC = ADDR + ('6番地、5番地' if A_P6 > A_P5 else '5番地、6番地')
assert LOC == 'A市C町二丁目6番地、5番地'
for x, y in UNI:
    assert SITE['F'][0] < x < SITE['A'][0] and SITE['A'][1] < y < SITE['C'][1]

# 建物図面の距離（筆界から外壁の面まで）
DN = round(SITE['C'][0] - O['o1'][0] - HALF, 2)      # 北：市道との筆界 → 乙建物の部分の北の外壁 2.83
DW = round(K['k4'][1] - HALF - SITE['A'][1], 2)      # 西：4番との筆界 → 甲建物の部分の西の外壁 1.93
DE = round(SITE['C'][1] - O['o2'][1] - HALF, 2)      # 東：7番との筆界 → 乙建物の部分の東の外壁 2.28
DS = round(K['k4'][0] - HALF - SITE['F'][0], 2)      # 南：南隣との筆界 → 南の外壁 2.93
assert (DN, DW, DE, DS) == (2.83, 1.93, 2.28, 2.93), (DN, DW, DE, DS)

# 価格（工事の直前）と持分（同一の者でないとみなした場合の持分。令別表十三の項申請情報欄ニ）
V_KOU, V_OTSU, V_ZOU, V_UNI = 450, 1350, 600, 2400       # 万円。増築工事費・工事後の建物の価額はひっかけ
assert V_KOU * 4 == V_KOU + V_OTSU
