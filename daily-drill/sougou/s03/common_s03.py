"""s03（建物区分登記・敷地権あり）の事案の共通データ。calc.py・form.py・draw.py が同じ座標・寸法から計算する（値を手で写さない）。
座標は X＝北・Y＝東（m）。建物の点は壁の中心線の交点。
事案：佐々木良子が、15番1・15番2の2筆にまたがる自分の非区分の建物（鉄筋コンクリート造2階建、1階店舗・2階居宅）を、
1階（店舗）と2階（居宅）に階層的に区分して、1階を会社に売る。土地も良子の単独所有なので、区分すると敷地権が生じる（区分所有法第22条第3項）。"""
import math
from fractions import Fraction

ADDR = 'A市E町二丁目'
OWNER_ADDR = 'A市E町二丁目15番2号'
OWNER = OWNER_ADDR + '　佐々木良子'
LOC = ADDR + '15番地2、15番地1'          # 床面積の多い部分の存する15番2が先（準則第88条第2項）
HOUSE0 = '15番2'                           # 区分前の家屋番号（登記記録）
HOUSE_I = 'E町二丁目15番2の1'               # （イ）1階の店舗部分
HOUSE_RO = 'E町二丁目15番2の2'              # （ロ）2階の居宅部分

# 土地：15番1（西）・15番2（東）・15番3（15番2の南、駐車場）
LAND = {'A': (530.00, 300.00), 'E': (530.00, 308.45), 'B': (530.00, 322.00),
        'C': (512.00, 322.00), 'F': (512.00, 308.45), 'D': (512.00, 300.00),
        'G': (505.00, 322.00), 'H': (505.00, 308.45)}
LOTS = {'15番1': ['A', 'E', 'F', 'D'], '15番2': ['E', 'B', 'C', 'F'], '15番3': ['F', 'C', 'G', 'H']}

# 一棟の建物（壁心）。外壁の厚さ0.20（中心線から外壁の面・内側の面まで0.10）
K = {'k1': (527.00, 302.50), 'k2': (527.00, 315.24), 'k3': (517.90, 315.24), 'k4': (517.90, 302.50)}
K2 = {'k1': K['k1'], 'k2': K['k2'], 'k5': (520.63, 315.24), 'k6': (520.63, 302.50)}   # 2階：北の壁・東西の壁は1階の真上
HALF = 0.10
# 1階北東の隅のメーターボックス（MB。両方の部分のメーターがある共用部分）：西の壁・南の壁の中心線の交点 p1。MBの壁の厚さ0.12（半分0.06）
P1 = (525.80, 313.74)
HALF_MB = 0.06

# 専有部分（内法）
IN_I = [(526.90, 302.60), (526.90, 313.68), (525.74, 313.68), (525.74, 315.14), (518.00, 315.14), (518.00, 302.60)]   # （イ）1階部分（MBを壁ごと除く）
IN_RO = [(526.90, 302.60), (526.90, 315.14), (520.73, 315.14), (520.73, 302.60)]                                       # （ロ）2階部分


def area(pts):
    s = 0.0
    for i in range(len(pts)):
        x0, y0 = pts[i]
        x1, y1 = pts[(i + 1) % len(pts)]
        s += x0 * y1 - x1 * y0
    return abs(s) / 2


def floor2(v):
    return math.floor(v * 100 + 1e-7) / 100


F1 = floor2(area(list(K.values())))       # 一棟1階 115.93
F2 = floor2(area(list(K2.values())))      # 一棟2階 81.15
FI = floor2(area(IN_I))                   # （イ）109.91
FR = floor2(area(IN_RO))                  # （ロ）77.37
assert (F1, F2, FI, FR) == (115.93, 81.15, 109.91, 77.37), (F1, F2, FI, FR)
# 内法の点が壁心の点から壁の厚さの半分だけ内側にあること
assert IN_I[0] == (round(K['k1'][0] - HALF, 2), round(K['k1'][1] + HALF, 2))
assert IN_I[1][1] == round(P1[1] - HALF_MB, 2) and IN_I[2][0] == round(P1[0] - HALF_MB, 2)
assert IN_RO[2] == (round(K2['k5'][0] + HALF, 2), round(K2['k5'][1] - HALF, 2))
# 敷地権の割合（規約がないので専有部分の床面積の割合。区分所有法第22条第2項・第14条）
NI, NR = round(FI * 100), round(FR * 100)
DEN = NI + NR
assert Fraction(NI, DEN).denominator == DEN and Fraction(NR, DEN).denominator == DEN    # 約分できない
R_I, R_RO = f'{DEN}分の{NI}', f'{DEN}分の{NR}'
assert (R_I, R_RO) == ('18728分の10991', '18728分の7737')
# 所在：15番1・15番2の上の一棟の床面積（1階＋2階）。15番2のほうが多い → 15番地2が先、家屋番号も15番2の…
YL = LAND['E'][1]
W1 = (YL - K['k1'][1]) * (9.10 + 6.37)
W2 = (K['k2'][1] - YL) * (9.10 + 6.37)
assert W2 > W1
for x, y in K.values():                    # 建物は15番1・15番2の中（15番3には掛からない）
    assert LAND['F'][0] < x - HALF and x + HALF < LAND['A'][0] and LAND['A'][1] < y - HALF and y + HALF < LAND['B'][1]
# 建物図面の距離（筆界から（ロ）部分＝一棟の北・西の外壁の面まで）
DN = round(LAND['A'][0] - K['k1'][0] - HALF, 2)     # 2.90
DW = round(K['k1'][1] - HALF - LAND['A'][1], 2)     # 2.40
assert (DN, DW) == (2.90, 2.40)
LOT_AREA = {n: area([LAND[k] for k in v]) for n, v in LOTS.items()}
assert {n: round(v, 2) for n, v in LOT_AREA.items()} == {'15番1': 152.10, '15番2': 243.90, '15番3': 94.85}

