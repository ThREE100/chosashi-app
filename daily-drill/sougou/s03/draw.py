_d.add('（ロ）部分の床面積', '12.54 × 6.17', '12.54 [×] 6.17 [=]')
_KEYS = [{'title': s_['title'], 'formula': s_['formula'], 'keys': s_['keys'], 'display': s_['display']} for s_ in _d.run()]
assert [round(_ck.val(s_) + 1e-9, 2) for s_ in _KEYS[:4]] == [DN, DW, EW, NS] and floor2(_ck.val(_KEYS[4])) == FR

