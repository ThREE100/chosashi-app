MADE_FILE = os.path.join(HERE, 'forms_made.json')   # {No: 問題ID}


def load_made():
    return json.load(open(MADE_FILE, encoding='utf-8')) if os.path.exists(MADE_FILE) else {}


def order(seed=SEED):
    """出題数が多いものほど先に出やすい重み付きの乱数順（重み＝出題数＋0.3。Efraimidis–Spirakis 法）。"""
    rnd = random.Random(seed)
    keys = []
    for no, grp, name, cnt in F:
        w = cnt + 0.3
        keys.append((rnd.random() ** (1.0 / w), no))
    return [no for _, no in sorted(keys, reverse=True)]


def main():
    made = load_made()
    by = {no: (grp, name, cnt) for no, grp, name, cnt in F}
    seq = order()
    L = ['# 書式ひな形の出題順（自動生成。`python3 daily-drill/forms_catalog.py`）', '',
         f'出題順は、過去問（H20〜R8）での出題数の目安が多いものほど先に出やすい重み付きの乱数順（seed={SEED}、重み＝出題数＋0.3）。作成済みは問題IDを付けた。',
         '出題数は、リポジトリの年度別記事の主題から数えた目安（公式の統計ではない）。', '',
         f'作成済み {len([n for n in seq if str(n) in made])}／{len(seq)} 書式。', '',
         '| 順 | No | 区分 | 書式 | 出題数 | 状態 |', '|---|---|---|---|---|---|']
    for i, no in enumerate(seq, 1):
        g, n, c = by[no]
        L.append(f'| {i} | {no} | {g} | {n} | {c} | {made.get(str(no), "**未作成**")} |')
    L += ['', '## 出題数の多い書式（目安）', '']
    for no, g, n, c in sorted(F, key=lambda x: -x[3])[:14]:
        L.append(f'- {n}（No.{no}）：{c}　{made.get(str(no), "未作成")}')
    os.makedirs(os.path.join(HERE, 'schedule'), exist_ok=True)
    open(os.path.join(HERE, 'schedule', 'forms-order.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    json.dump([{'order': i, 'no': no, 'group': by[no][0], 'name': by[no][1], 'count': by[no][2], 'made': made.get(str(no), '')} for i, no in enumerate(seq, 1)],
              open(os.path.join(HERE, 'schedule', 'forms-order.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    todo = [no for no in seq if str(no) not in made]
    print('作成済み', len(made), '／未作成', len(todo), '／未作成の先頭5つ（出題順）:', [(no, by[no][1]) for no in todo[:5]])


if __name__ == '__main__':
    main()
