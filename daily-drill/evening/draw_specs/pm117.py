def _lim(F, a, b):
    """規則第10条第4項の誤差の限度（国土調査法施行令別表第四）：(a ＋ b × F^(1/4)) × √F を小数第2位未満切捨て"""
    return math.floor((a + b * F ** 0.25) * math.sqrt(F) * 100) / 100


