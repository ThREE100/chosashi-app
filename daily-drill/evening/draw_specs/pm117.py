def _area(names):
    f = [(Fraction(str(P[n][0])), Fraction(str(P[n][1]))) for n in names]
    a = abs(sum(f[i][0] * f[(i + 1) % len(f)][1] - f[(i + 1) % len(f)][0] * f[i][1] for i in range(len(f)))) / 2
    assert 0.03 < float(a * 100) % 1 < 0.97, (names, float(a))   # 切捨ての境目を避ける
    return math.floor(a * 100) / 100


