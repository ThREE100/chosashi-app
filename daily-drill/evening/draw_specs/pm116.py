LEN = {}
for a, b in SIDES:
    v = math.hypot(P[a][0] - P[b][0], P[a][1] - P[b][1])
    assert abs((v * 100) % 1 - 0.5) > 0.06, (a, b, v)       # 四捨五入の境目を避ける
    LEN[a + b] = round(v + 1e-12, 2)


def _area(names):
    f = [(Fraction(str(P[n][0])), Fraction(str(P[n][1]))) for n in names]
    a = abs(sum(f[i][0] * f[(i + 1) % len(f)][1] - f[(i + 1) % len(f)][0] * f[i][1] for i in range(len(f)))) / 2
    assert 0.03 < float(a * 100) % 1 < 0.97, (names, float(a))   # 切捨ての境目を避ける
    return math.floor(a * 100) / 100


A1, A2, A3 = _area('AEFD'), _area('EGHF'), _area('GBCH')
REGA = 613.75
assert 0 < abs(A1 + A2 + A3 - REGA) < 1.0
