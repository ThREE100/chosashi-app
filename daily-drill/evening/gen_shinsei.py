def B(law, art, quote):
    return {'law': law, 'article': art, 'quote': quote}


def area(pts):
    s = 0.0
    for i in range(len(pts)):
        x0, y0 = pts[i]
        x1, y1 = pts[(i + 1) % len(pts)]
        s += x0 * y1 - x1 * y0
    return abs(s) / 2


def floor2(v):
    import math
    return math.floor(v * 100 + 1e-9) / 100


