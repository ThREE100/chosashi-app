def lerp(p, q, t):
    return (round(p[0] + (q[0] - p[0]) * t, 2), round(p[1] + (q[1] - p[1]) * t, 2))


PTS['E'] = lerp(PTS['B'], PTS['C'], 0.55)
PTS['F'] = lerp(PTS['A'], PTS['D'], 0.55)
POLYS = {'total': ['A', 'B', 'C', 'D'], 'i': ['A', 'B', 'E', 'F'], 'ro': ['F', 'E', 'C', 'D']}
