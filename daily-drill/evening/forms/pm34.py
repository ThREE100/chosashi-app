"""PM-34　土地分合筆登記（書式一覧 No.15）"""
import math
from common import B, HO, KI, REI, REI0, TOUMEN, JUN, area, floor2, field, f_date, f_agent, fig_generic


def kou(F, k=1):
    """精度区分 甲2の誤差の限度（k=2で甲3）。(0.05＋0.01×F^(1/4))×√F、小数第2位未満切捨て。"""
    return floor2(k * (0.05 + 0.01 * F ** 0.25) * math.sqrt(F))


# 20番1（西）の東の帯（E・B・C・H）を分けて、東に接する21番に合わせる。
P = {'A': (530.00, 300.00), 'E': (530.00, 312.85), 'B': (530.00, 315.40), 'F': (530.00, 325.03),
     'G': (516.20, 325.03), 'C': (516.20, 315.40), 'H': (516.20, 312.60), 'D': (516.20, 300.00)}
REG1, REG21 = 211.50, 131.90
a_i = floor2(area([P[k] for k in 'AEHD']))       # 13.80×（12.85＋12.60）÷2＝175.605→175.60
a_ro = floor2(area([P[k] for k in 'EBCH']))      # 13.80×（2.55＋2.80）÷2＝36.915→36.91
a_21 = floor2(REG21 + a_ro)                       # 合筆後の21番は登記記録＋（ロ）
k2, k3 = kou(REG1), kou(REG1, 2)
diff = round(a_i + a_ro - REG1, 2)
assert (a_i, a_ro, a_21) == (175.60, 36.91, 168.81) and (k2, k3) == (1.28, 2.56) and diff == 1.01 and diff <= k2, (a_i, a_ro, k2, k3, diff)
assert floor2(area([P[k] for k in 'BFGC'])) == 132.89     # 21番を座標で測ると132.89（登記記録131.90とは別の値）

