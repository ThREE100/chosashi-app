# 壁心の寸法（m）。縦割りの二世帯。外壁・界壁とも厚さ0.20（中心線から内側の面まで0.10）
W, D, W_I = 14.00, 8.05, 7.85
W_RO = round(W - W_I, 2)
T = 0.10
toh = floor2(W * D)                                   # 一棟（壁心）各階 112.70
u_i = floor2((W_I - 2 * T) * (D - 2 * T))             # （イ）内法 7.65×7.85＝60.0525 → 60.05
u_ro = floor2((W_RO - 2 * T) * (D - 2 * T))           # （ロ）内法 5.95×7.85＝46.7075 → 46.70
assert (W_RO, toh, u_i, u_ro) == (6.15, 112.70, 60.05, 46.70), (W_RO, toh, u_i, u_ro)
n_i, n_ro = round(u_i * 2 * 100), round(u_ro * 2 * 100)   # 各階の合計を100倍した整数
den = n_i + n_ro
assert (n_i, n_ro, den) == (12010, 9340, 21350)
wrong_hekishin = floor2(W_I * D)                      # 壁心で測った誤答 63.19
assert wrong_hekishin == 63.19

