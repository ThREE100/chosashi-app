"""PM-43　区分建物表題部変更登記（増築による床面積の変更。書式一覧 No.57）"""
from common import B, HO, KI, REI, REI0, JUN, area, floor2, field, f_date, f_agent, en_to_xy

# 壁心（m）。縦割り：西（イ）5番の1 6.00、東（ロ）5番の2 6.00、南北8.00。1階・2階同じ形。壁の厚さ0.20（中心線から内側の面まで0.10）
# （ロ）の1階の東に、南の外壁にそろえて東西2.73・南北4.55（壁心）を増築。元の東の外壁は、出入口を設けて残した（専有部分の中の壁になる）
ORG = (500.00, 300.00)       # 本件一棟の南西の角（壁の中心線）を X・Y の原点にとった座標
P = en_to_xy(ORG, {
    # 一棟の1階（壁心、増築後）
    'w0': (0, 0), 'w1': (14.73, 0), 'w2': (14.73, 4.55), 'w3': (12.00, 4.55), 'w4': (12.00, 8.00), 'w5': (0, 8.00),
    # （ロ）の1階（内法、増築後）：界壁の内側 6.10、南の内側 0.10、増築部分の東の内側 14.63、北の内側 4.45、元の東の外壁の内側 11.90、北の外壁の内側 7.90
    'r0': (6.10, 0.10), 'r1': (14.63, 0.10), 'r2': (14.63, 4.45), 'r3': (11.90, 4.45), 'r4': (11.90, 7.90), 'r5': (6.10, 7.90),
})
toh_b = floor2(12.00 * 8.00)
toh_a1 = floor2(area([P[k] for k in ('w0', 'w1', 'w2', 'w3', 'w4', 'w5')]))
ro_b = floor2(5.80 * 7.80)
ro_a1 = floor2(area([P[k] for k in ('r0', 'r1', 'r2', 'r3', 'r4', 'r5')]))
assert (toh_b, toh_a1, ro_b, ro_a1) == (96.00, 108.42, 45.24, 57.11), (toh_b, toh_a1, ro_b, ro_a1)
wrong_wall = floor2(5.80 * 7.80 + 2.53 * 4.35)       # 元の外壁の分を引いた誤答 56.24
wrong_hk = floor2(5.80 * 7.80 + 2.73 * 4.55)         # 増築部分を壁心で足した誤答 57.66
assert (wrong_wall, wrong_hk) == (56.24, 57.66)

