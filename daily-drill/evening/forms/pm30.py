"""PM-30　区分建物の合体による登記等（合体後に区分建物でない建物となる場合。書式一覧 No.73）"""
from common import B, HO, KI, REI, REI0, floor2, field, f_date, f_agent

# 壁心（m）。縦割りの2個の区分建物：西3番の1 6.37、東3番の2 5.46、南北7.28。1階・2階同じ形。壁の厚さ0.15（中心線から内側の面まで0.075）
W1, W2, D, T = 6.37, 5.46, 7.28, 0.075
toh = floor2((W1 + W2) * D)                     # 一棟（壁心）11.83×7.28＝86.1224 → 86.12
u1 = floor2((W1 - 2 * T) * (D - 2 * T))         # 6.22×7.13＝44.3486 → 44.34
u2 = floor2((W2 - 2 * T) * (D - 2 * T))         # 5.31×7.13＝37.8603 → 37.86
assert (toh, u1, u2) == (86.12, 44.34, 37.86), (toh, u1, u2)
wrong_sum = round(u1 + u2, 2)                    # 内法の合計の誤答 82.20
assert wrong_sum == 82.20

