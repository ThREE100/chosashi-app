    C_true = P(541.30, 318.00)
    base = cmath.phase(T2 - T1)
    ang = dms((cmath.phase(C_true - T1) - base) % (2 * math.pi))
    dist = round(abs(C_true - T1), 2)
    C = r2(T1 + cmath.rect(dist, base + dms_rad(ang)))
    K1, K2 = P(556.40, 300.09), P(545.20, 300.07)             # 西隣地の地積測量図
    S = P(540.90, 312.20)                                      # 南隣地の地積測量図
    Dz = inter(K1, K2, C, S)
    D = r2(Dz)
    E = r2(A + (B - A) / abs(B - A) * D_AE)
    F = r2(D + (C - D) / abs(C - D) * D_DF)
    Cz = T1 + cmath.rect(dist, base + dms_rad(ang))
    Ez, Fz = A + (B - A) / abs(B - A) * D_AE, D + (C - D) / abs(C - D) * D_DF
    for nm, z in (('C', Cz), ('D', Dz), ('E', Ez), ('F', Fz)):          # 四捨五入の境目（x.xx5）に近い値を避ける
        for u in (z.real, z.imag):
            assert abs((u * 100) % 1 - 0.5) > 0.08, (nm, u)
    ai, ar = floor2(shoelace([A, E, F, D])), floor2(shoelace([E, B, C, F]))
    tot = round(ai + ar, 2)
    diff = round(tot - REG, 2)
    kk = math.floor(kou2(REG) * 100 + 1e-9) / 100
    need = abs(diff) > kk
    assert need and abs(diff) < 2 * kk, (diff, kk)
    assert abs(abs(diff) - kk) > 0.3
