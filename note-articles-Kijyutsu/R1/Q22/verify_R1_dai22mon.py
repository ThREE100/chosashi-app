def poly_area(pts):
    n = len(pts)
    return abs(sum(pts[i][0] * pts[(i + 1) % n][1] - pts[(i + 1) % n][0] * pts[i][1] for i in range(n))) / 2


def trunc2(v):
    """床面積・地積（宅地）の端数処理：1平方メートルの100分の1未満を切り捨て。"""
    return math.floor(v * 100 + 1e-9) / 100


def rect(y0, x0, y1, x1):
    return [(y0, x0), (y1, x0), (y1, x1), (y0, x1)]


