assert round(poly_area([(0, 0), (25.5, 0), (25.5, 9), (15.5, 9), (15.5, 6.5), (0, 6.5)]), 2) == 190.75
assert round(poly_area([(0, 0), (25.5, 0), (25.5, 9), (23.5, 9), (23.5, 6.5), (7, 6.5), (7, 4.5), (0, 4.5)]), 2) == 156.75

