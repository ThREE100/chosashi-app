#!/usr/bin/env python3
"""不動産登記法編（sokatsu-02-fudousan-touki-hou.md）を、章ごとの9本の記事に分割し、
総合記事を「入り口とまとめ」に再構成する（2026-10-13に1回だけ実行した）。
入力は分割前の総合記事（assemble.py → postprocess.py の出力）。分割後の総合記事には章の本文がないので、再実行はできない。
章の記事の体裁は民法編の章分割（postprocess.py の split_minpou）にそろえた（論点の見出しは ###、タイトルは ##）。
使い方: python3 tools/drill/sokatsu/split_fudousan.py <分割前の総合記事.md>   （リポジトリ直下で実行）"""
import re, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from postprocess import reflow, norm, TYPE_LINES, COL

HUB = 'sokatsu-02-fudousan-touki-hou.md'
STEM = 'sokatsu-02-fudousan-touki-hou'
PRE = ['PA', 'PB', 'PC', 'PD', 'PE', 'PF1', 'PF2', 'PG1', 'PG2']
CIR = '①②③④⑤⑥⑦⑧⑨'
SHORT = ['申請人・代位・代理・一括申請・表題部所有者', '添付情報・電子申請・登記識別情報・保存期間・登録免許税', '土地の表題・地目・地積・地図・地積測量図・筆界特定', '土地の分筆・合筆・地積更正', '建物の認定・床面積・建物図面・表題部の変更と滅失', '建物の分割・分棟・合併', '建物の合体による登記等', '敷地権', '区分建物の表示と共用部分']
TAG = ['誰が、何を添えて、どこまでまとめて申請できるか', '申請の「付属品」と「手続の作法」を一気に整理', '地目・地積・地図・筆界特定を一気に整理', '分筆・合筆の制限と例外を整理', '建物の個数・床面積・図面・滅失を整理', '合併できない場合と、分割・分棟を整理', '合体とは何かと、権利の引継ぎを整理', '敷地権の要件・登記・添付情報を整理', '区分建物の申請人・申請方法・共用部分を整理']
TITLE = '【土地家屋調査士受験生向け】直前期の苦手論点つぶし総合記事②不動産登記法編'
HUBLINK = f'[総合記事②不動産登記法編]({HUB})'

def fn(k): return f'{STEM}-ch{k + 1}.md'
def link(k): return f'[第{k + 1}章 {SHORT[k]}]({fn(k)})'

def main(src):
    L = pathlib.Path(src).read_text(encoding='utf-8').split('\n')
    def idx(p): return next(i for i, l in enumerate(L) if l.startswith(p))
    cs = [idx(f'### 不動産登記法{c}') for c in CIR]
    i_cross, i_app, i_last = idx('### 章をまたいで出る論点'), idx('### 付録'), idx('### 最後に')
    i_use, i_whole, i_types, i_toc = idx('### この記事の使い方'), idx('### 誤答の全体像'), idx('### 誤答の10の型'), idx('### 目次')
    def strip(seg):
        seg = list(seg)
        while seg and seg[-1].strip() in ('', '---'): seg.pop()
        return seg
    chunks = [strip(L[cs[k]:(cs + [i_cross])[k + 1]]) for k in range(9)]
    app_lines = [l for l in L[i_app:i_last] if re.match(r'^- D\d{4} ', l)]
    assert len(app_lines) == 47
    sub = [[l for l in app_lines if f'（{PRE[k]}-' in l] for k in range(9)]
    assert sum(map(len, sub)) == 47
    info, topics = [], []
    for k in range(9):
        t = '\n'.join(chunks[k])
        n = int(re.search(r'\*\*この章の対象\*\*：(\d+)肢', t).group(1))
        m = int(re.search(r'(\d+)つ?の論点にまとめています', t).group(1))
        tp = [l[5:] for l in chunks[k] if l.startswith('#### 【')]
        assert len(tp) == m
        info.append((n, m)); topics.append(tp)
    assert sum(i[0] for i in info) == 370 and sum(i[1] for i in info) == 89

    # ---- 章の記事 ----
    for k in range(9):
        n, m = info[k]
        o = [f'## {TITLE}（{k + 1}/9）{SHORT[k]}〜{TAG[k]}〜', '', '**対象科目：不動産登記法（択一式）**', '']
        o.append(f'この記事は、択一式の一問一答で**繰り返し間違えている肢、または「わからない」と答えた肢**を科目ごとにまとめた総合記事のうち、不動産登記法編（370肢・89論点・9章）を、章ごとに分けた**第{k + 1}章**です。対象は{n}肢で、{m}つの論点に整理しています。同じ論点・似た論点は1つの論点にまとめ、肢ごとの判定は各論点の最後に置いています。')
        o.append('')
        o.append(f'全体の入り口とまとめは{HUBLINK}です。章どうしは参照し合わないので、苦手な章から読んで構いません。')
        o += ['', '---', '', '### この記事の使い方', '',
              '1. まず、下の「誤答の10の型」を読みます。自分の間違い方の癖に名前を付けておくと、肢を読むときに「今これを疑っている」と自覚できます。',
              '2. 論点を順に読みます。各論点は「結論 → 中身の整理 → たとえば → なぜ繰り返し間違えるのか → 判断のしかた → 肢ごとの判定」の順です。時間がない日は、結論と判断のしかた、章末の直前チェックだけでも一周できます。',
              '3. 最後に、付録の「最優先で潰す肢」で仕上げます。',
              '', '不動産登記法の肢は、**何の登記か → 誰が申請するか → まとめて申請できるか → 何を添付するか → いつまでか**の順に確認します。',
              '', '正誤の基準は**現行法令**です。出題当時と法令が変わった肢は、その旨を注記しています。「実務の取扱いによる」「条文に明記はない」と書いた項目は、条文を追っても直接の根拠が確認できない暗記項目です。理屈で解こうとせず、結論を覚えてください。',
              '', '---', '', '### 誤答の10の型', '',
              '各肢の誤答の原因を、最も近い型に分けています。実際にどう考えたかは本人にしか分かりませんから、型は「考えられる原因」の目安です。', '']
        o += [f'- 型{t}　{nm}：{d}' for t, nm, d in TYPE_LINES]
        o += ['', f'全体版（直し方と、型ごとに目立つ論点つき）は{HUBLINK}にあります。', '', '---', '', '### この章の論点', '']
        o += ['- ' + t for t in topics[k]]
        o += ['', '---', '']
        body = []
        for l in chunks[k][1:]:
            if l.startswith('#### '): l = '### ' + l[5:]
            body.append(l)
        bt = '\n'.join(body)
        bt = re.sub(r'\*\*この章の対象\*\*：[^\n]*\n', '', bt)
        bt = bt.replace('**この章の誤りの傾向**\n', '### この章の誤りの傾向\n').replace('**この章の直前チェック**\n', '### この章の直前チェック\n')
        o += [bt.strip('\n'), '', '---', '', '### 付録　最優先で潰す肢（誤答が3回以上の肢）', '']
        if sub[k]:
            o += [f'誤答が3回以上に達した肢の一覧です（{len(sub[k])}肢）。誤答が多い順に並べ、〇×は正解、カッコ内は解説した論点です。試験直前は、まずここを声に出して判定し、迷った肢だけ該当の論点に戻ります。', '']
            o += sub[k]
        else:
            o.append('この章には、誤答が3回以上の肢はありません。')
        o += ['', '---', '', '### 次に読む', '']
        if k < 8: o.append(f'次は、{link(k + 1)}です。')
        else: o.append(f'章の記事は以上です。章をまたぐ串刺しチェックと、誤答3回以上の47肢の一覧は、{HUBLINK}にあります。')
        if k > 0: o += ['', f'前の記事は、{link(k - 1)}です。']
        o += ['', 'この記事の統計と分類は、択一式の一問一答の解答履歴に基づく個人用の分析です。']
        text = reflow('\n'.join(o))
        (COL / fn(k)).write_text(text, encoding='utf-8')

    # ---- 総合記事（入り口とまとめ） ----
    H = [L[0], '', '**対象科目：不動産登記法（択一式）**', '']
    H.append('この記事は、択一式の一問一答で**繰り返し間違えている肢、または「わからない」と答えた肢**を、科目ごとに集めて一気に読めるようにまとめた総合記事（全3本）の**不動産登記法編**です。対象は370肢と最も多く、全体の約8割を占めます。同じ論点・似た論点は1つの論点にまとめて統合して解説し、肢ごとの判定は各論点の最後に置いています。')
    H += ['', '分量が多いため、不動産登記法編は**章ごとの9本の記事**に分けました。**この記事は、その9本の入り口とまとめ**です。ここで「誤答の型」と全体像をつかみ、章の記事で個別の論点を読み、最後にここへ戻って「串刺しチェック」と「最優先肢」で仕上げます。']
    H += ['', '不動産登記法は、択一式の問4〜問19に出る分野です。ここで間違える肢は、条文の数は多くても、確認する観点は5つに集約できます。', '', '**何の登記か → 誰が申請するか → まとめて申請できるか → 何を添付するか → いつまでか**', '', 'この5つの順で肢を読む癖をつけることが、この記事の最大の目的です。', '', 'この科目の370肢は、89の論点に整理し、9章に分けています。', '', '---', '', '### 9本の章の記事（目次）', '',
          '章の番号（①〜⑨）と、論点ID（【PA-1】など）の頭文字は対応しています。各章の記事には、その章の論点の結論・整理・肢ごとの判定・直前チェックと、その章の最優先肢が入っています。', '']
    for k in range(9):
        n, m = info[k]
        H += [f'#### {CIR[k]} {link(k)}', '', f'{n}肢・{m}論点（論点ID：{PRE[k]}-1〜{PRE[k]}-{m}）。{TAG[k]}。誤答3回以上の最優先肢は{len(sub[k])}肢。', '']
        H += ['- ' + t for t in topics[k]]
        H.append('')
    H += ['**読む順番の目安**', '',
          '- 通して読むなら①→⑨の順。申請の基本（①②）→土地（③④）→建物（⑤⑥⑦）→区分建物（⑧⑨）と、基本から応用へ進みます。',
          '- 苦手がはっきりしているなら、「最優先肢」の件数が多い章（⑧は12肢、②と④は各7肢）から読みます。付録の一覧で、自分の迷う肢がどの章に属するかを確かめてください。',
          '- 土地の問題が先なら③④、建物と区分建物なら⑤〜⑨をまとめて読んでも構いません。章は互いに独立しています。', '', '---', '',
          '### この記事の使い方', '',
          '1. **まず「誤答の型」を読む**（約10分）。自分の間違い方の癖を、10の型に分けて説明しています。型の名前を覚えておくと、肢を読むときに「今これを疑っている」と自覚できます。',
          '2. **章の記事を順に読む**（上の目次）。各章は「論点の見出し → 結論 → 中身の整理 → たとえば → なぜ繰り返し間違えるのか → 判断のしかた → 肢ごとの判定」の順です。時間がない日は、結論と判断のしかた、章末の「この章の直前チェック」だけでも一周できます。',
          '3. **串刺しチェックで横に確認する**。別々の章で出る似た論点を、横に並べ直しています。章の記事を読み終えたら、ここに戻ってください。',
          '4. **付録の「最優先で潰す肢」で仕上げる**。誤答が3回以上に達した肢の一覧です。試験直前の見直しは、ここだけで十分です。各章の記事の末尾にも、その章の分だけを載せています。', '']
    H += [l for l in L[i_use + 1:i_whole] if False]
    para = next(l for l in L[i_use:i_whole] if l.startswith('正誤の基準'))
    H += [para, '', '---', '']
    H += strip(L[i_whole:i_toc]) + ['', '---', '', '### 論点IDと記事の対応', '', '串刺しチェックと付録は、論点IDで書いています。IDの頭文字から、その論点が載っている記事（章）がわかります。', '']
    H += [f'- 【{PRE[k]}-n】… {link(k)}' for k in range(9)]
    H += ['', '---', ''] + strip(L[i_cross:i_app]) + ['', '---', ''] + strip(L[i_app:i_last]) + ['', '---', '']
    last = strip(L[i_last:])
    H += last[:-1] if False else last
    H = '\n'.join(H)
    old = '迷ったら、令別表の項と規則第35条に戻ってください。'
    assert old in H
    H = H.replace(old, old + '\n\n9本の章の記事を読み終えたら、この記事の「串刺しチェック」で章をまたいで確認し、「最優先で潰す肢」を声に出して判定してください。迷った肢は、論点IDの頭文字（【PA-n】〜【PG2-n】）から該当する章の記事に戻れます。', 1)
    pathlib.Path(COL / HUB).write_text(reflow(H), encoding='utf-8')

if __name__ == '__main__':
    main(sys.argv[1])
