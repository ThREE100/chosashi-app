def parse_topics(text):
    topics = collections.OrderedDict()
    cur = None
    lines = {}
    for ln in text.split('\n'):
        m = re.match(r'^#### 【([A-Z0-9]+-\d+)】(.*)$', ln)
        if m:
            cur = m.group(1); topics[cur] = m.group(2).strip(); continue
        m = re.match(r'^- (D\d{4}) ([〇×])(.*)$', ln)
        if m and cur:
            lines[m.group(1)] = (cur, m.group(2), m.group(3).strip())
    return topics, lines

def chapter_title(text):
    return text.split('\n')[0].lstrip('# ').strip()

def stats(subject):
    L = [o for o in data.values() if o['subject'] == subject]
    ev = [(o, h) for o in L for h in o['history'] if h[2] != 'k']
    mis = sum(1 for _, h in ev if h[2] == 'm'); unk = sum(1 for _, h in ev if h[2] == 'u')
    t2x = sum(1 for o, h in ev if h[2] == 'm' and o['truth'])
    f2o = sum(1 for o, h in ev if h[2] == 'm' and not o['truth'])
    ever_t2x = len({o['id'] for o, h in ev if h[2] == 'm' and o['truth']})
    ever_f2o = len({o['id'] for o, h in ev if h[2] == 'm' and not o['truth']})
    only_unk = sum(1 for o in L if o['miscon'] == 0)
    only_mis = sum(1 for o in L if o['unknown'] == 0)
    both = len(L) - only_unk - only_mis
    tr = sum(1 for o in L if o['truth'])
    return dict(n=len(L), mis=mis, unk=unk, t2x=t2x, f2o=f2o, ever_t2x=ever_t2x, ever_f2o=ever_f2o,
                only_unk=only_unk, only_mis=only_mis, both=both, w2=sum(1 for o in L if o['W'] >= 2),
                w3=sum(1 for o in L if o['W'] >= 3), w5=sum(1 for o in L if o['W'] >= 5),
                true_n=tr, false_n=len(L) - tr, pair=sum(1 for o in L if o['pair']))

def tag_section(key, chapters, topics_titles, tags):
    sub = ARTICLES[key]['subject']
    ids = [i for i in tags if data[i]['subject'] == sub]
    prim = collections.Counter(tags[i]['primary'] for i in ids)
    sec = collections.Counter(tags[i]['secondary'] for i in ids if tags[i].get('secondary'))
    out = []
    order = sorted(TAGNAME, key=lambda t: -(prim[t] + sec[t]))
    for t in order:
        if prim[t] + sec[t] == 0:
            continue
        g = collections.Counter(tags[i]['group'] for i in ids if tags[i]['primary'] == t)
        top = g.most_common(3)
        ex = '、'.join(f'【{gid}】{short_title(topics_titles[gid])}（{c}肢）' for gid, c in top)
        d, a = TAGDESC_OVR.get(key, {}).get(t, TAGDESC[t])
        out.append(f'#### 型{t}　{TAGNAME[t]}（主な原因{prim[t]}肢・副次的な原因{sec[t]}肢）')
        out.append(f'**どんな間違いか**：{d}')
        if top:
            out.append(f'**この科目で目立つ論点**：{ex}')
        out.append(f'**対策**：{a}')
        out.append('')
    return '\n'.join(out), prim, sec

def priority_list(subject, lines, min_w=3):
    L = sorted([o for o in data.values() if o['subject'] == subject and o['W'] >= min_w],
               key=lambda o: (-o['W'], o['id']))
    out = []
    for o in L:
        g, tf, txt = lines[o['id']]
        txt = re.sub(r'★誤答\d+回', '', txt).strip()
        out.append(f'- {o["id"]} {tf}（{g}）誤答{o["W"]}回：{txt}')
    return out

def toc(chapters_text, key):
    out = []
    for ch, t in chapters_text:
        out.append(f'- {chapter_title(t)}')
        tp, _ = parse_topics(t)
        for gid, title in tp.items():
            out.append(f'  - 【{gid}】{title}')
    return '\n'.join(out)

def check_refs(text, allids):
    for m in re.findall(r'【([A-Z0-9]+-\d+)】', text):
        if m not in allids:
            raise SystemExit(f'未定義の論点参照: {m}')

