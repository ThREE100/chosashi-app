"""Codex用・ChatGPT（GitHub接続）用の貼り付け文を作る。ひっかけ診断ノートの instructions() と同じ文面に、
図の添付（Claudeが作った図のPNG）を足した汎用版。"""
REPO = 'https://github.com/ThREE100/chosashi-app/blob/main/'
RAW = 'https://raw.githubusercontent.com/ThREE100/chosashi-app/main/'


def instructions(label, prompts_rel, pages, file_prefix, kata_rel, figs=None):
    """label: 「一枚まとめ B-01」など。prompts_rel / kata_rel：リポジトリの中のパス。figs: [(ページ, 図の名前, リポジトリの中のパス)]。"""
    n = len(pages)
    heads = [f"## {k}ページ目：{p['caption']}" for k, p in enumerate(pages, 1)]
    figs = figs or []
    figpages = {}
    for k, name, rel in figs:
        figpages.setdefault(k, []).append((name, rel))
    fig_list = [f"- {k}ページ目：{name}.png　{RAW}{rel}" for k, name, rel in figs]
    cx = [f"# Codexに貼る指示文（{label} 学習まんが・全{n}ページ＋見出し画像2枚）", "",
          "使い方：「ここから」〜「ここまで」をそのまま OpenAI Codex に貼り、キャラクターシート_トリ先生_01〜03 と キャラクターシート_I-01〜03 の6枚を添付する（シートはリポジトリにない）。", "",
          "---ここから---", "",
          "GitHub のリポジトリ ThREE100/chosashi-app（https://github.com/ThREE100/chosashi-app 、ブランチ main）にある学習まんがのプロンプトで、画像を作ってください。", "",
          "## 対象（ここから読む）", f"- プロンプト：{REPO}{prompts_rel}", f"- 構成の型（確認用）：{REPO}{kata_rel}"]
    if figs:
        cx += ["- 差し込む図（リポジトリの中の正確な図。描き直さずにそのまま使う）："] + ["  " + x for x in fig_list]
    cx += ["", "## 手順", "1. リポジトリを clone する（手元にあれば git pull origin main）。", "   git clone https://github.com/ThREE100/chosashi-app.git && cd chosashi-app",
           f"2. プロンプトのファイルの「## 1ページ目」〜「## {n}ページ目」と「## 見出し画像（note用 1280×670）」「## 見出し画像（Instagram用 1080×1440）」の見出しの下にある ``` で囲まれたプロンプトを読む。コードブロックの中身を1文字も変えずに使う（要約・翻訳・言い換えをしない）。",
           "3. 添付した6枚を参照画像として渡し、プロンプト1つにつき1枚ずつ生成する。「キャラクターシート_トリ先生_01, _02, _03」は鳥の3枚、「キャラクターシート_I-01, I-02, I-03」は女性の3枚。鳥が先生、女性が生徒。"]
    if figs:
        cx += ["   図のあるページは、リポジトリの図のPNGも参照画像として渡す。生成した後、`python3 tools/gakushu_manga/paste_fig.py <生成した画像> <プロンプトのファイル> <ページ番号>` を実行して、正確な図を枠に貼り直す（図が崩れていなくても必ず行う）。"]
    cx += [f"4. 画像を「{file_prefix}_p01.png」〜「{file_prefix}_p{n:02d}.png」「{file_prefix}_見出し_note.png」「{file_prefix}_見出し_IG.png」の名前で、リポジトリの外の作業フォルダに PNG で保存する。指定の大きさでなければ、縦横比を保って拡大・縮小し全体を覆ってから中央で切り取る（歪ませない。余白を足さない。透明の部分を残さず RGB）。",
           "5. 各ページを確かめ、問題があればそのページだけ同じプロンプトで1回作り直す（2回目も直らなければ、そのまま渡して何が直らなかったかを報告する）。",
           "   - コマの数と配置がプロンプトの「## 2. Page layout」のとおり",
           "   - 文字がプロンプトの文字列と一字一句同じで、ほかの文字がない。漢字が中国の字体になっていない",
           "   - 名前・役割名（トリ先生・先生・生徒など）がどこにもない。吹き出しのしっぽが話し手を指している",
           "   - 生徒は I-01〜03 の顔・髪型・服装のままで、鳥の先生と同じ画風。腕は左右1本ずつ、手は2つで指は5本ずつ",
           "   - Ａ・Ｂ・Ｃは顔のないピクトグラム。既存の漫画作品に似た画風・キャラクターになっていない。背景が端まで塗られている"]
    if figs:
        cx += ["   - 図の枠の中が、リポジトリの図と同じ（線・点・文字・数字が1つも変わっていない）。枠に人物・吹き出しが重なっていない"]
    cx += ["6. すべての画像と、手順5の確認結果（ページごとに、できた点・崩れた点を具体的に）を報告する。", "",
           "## してはいけないこと", "- リポジトリのファイルを書き換えない。リポジトリの中に画像を置かない。git の commit・push はしない。", "", "---ここまで---", ""]

    gp = [f"# ChatGPTに貼る指示文（GitHubから直接読み込ませる形・{label} 学習まんが）", "",
          f"使い方：GitHubと接続したChatGPTに、キャラクターシート_トリ先生_01〜03 と キャラクターシート_I-01〜03 の6枚を添付し、「ここから」〜「ここまで」を貼る。1回の返事で1ページだけ作らせ、2ページ目からは同じチャットで下の1行を送る（全{n}ページ＋見出し画像2枚）。",
          f"ChatGPTがリポジトリを読めなかったときは、`{prompts_rel}` の該当ページのコードブロックの中身を、そのまま全文貼る（6枚の添付と一言はそのまま）。"]
    if figs:
        gp += ["", "**図のあるページ**（下の一覧）は、そのページの図のPNGを、上のURLから保存して一緒に添付する（ChatGPTに図を描かせない。添付した図をそのまま置かせる）。"
               "生成された画像で図が崩れていたら、手元で `python3 tools/gakushu_manga/paste_fig.py <生成した画像> " + prompts_rel + " <ページ番号>` を実行すると、正確な図が枠に貼り直される。", ""] + fig_list
    gp += ["", "---ここから---", "", "接続しているGitHubのリポジトリ ThREE100/chosashi-app（ブランチ main）から、次のファイルを読んでください。", f"{REPO}{prompts_rel}", "",
           f"このファイルの見出し「{heads[0]}」の下にある ``` で囲まれたプロンプトを、1文字も変えずに（要約・翻訳・言い換えをせずに）使って、画像を1枚作ってください。コードブロックの外の説明文と、ほかの見出しのプロンプトは使いません。", "",
           "- 添付した6枚のうち、鳥の3枚（キャラクターシート_トリ先生_01〜03）が先生、女性の3枚（キャラクターシート_I-01〜03）が生徒です。",
           "- 名前・役割名は画像のどこにも書かないでください。話し手は、絵と吹き出しのしっぽで見分けます。",
           "- 大きさは 1024×1536（縦長）。作るのはこの1ページだけです。"]
    if figs:
        gp += ["- プロンプトに「FIGURE SLOT」があるページでは、添付した図の画像を、指定の枠にそのまま置いてください。図を描き直したり、線・文字・数字を変えたりしないでください。"]
    gp += [f"- 作る前に、読み込んだプロンプトの最初の1行（「Draw page 1 of {n} …」で始まる行）をそのまま返事に書いて、正しいプロンプトを読めたことを示してから画像を作ってください。読めなかったときは、画像を作らずに「読めなかった」と答えてください。", "",
           "---ここまで---", "", "2ページ目以降は、同じチャットで次の1行だけを送る（○に数字）。図のあるページは、その図のPNGを添付してから送る。",
           "「同じファイルの『## ○ページ目：…』の見出しの下のプロンプトで、同じやり方で次の1枚を作ってください。最初の1行を書いてから作ってください。」", "",
           "見出し画像は、次の1行を送る（大きさはプロンプトのとおり）。",
           "「同じファイルの『## 見出し画像（note用 1280×670）』の見出しの下のプロンプトで、同じやり方で1枚作ってください。最初の1行を書いてから作ってください。」（Instagram用は見出しを『## 見出し画像（Instagram用 1080×1440）』に替える）", "",
           "ページの見出し一覧（コピー用。図を添付するページに印）：", ""]
    gp += [f"- {h}" + ("　← 図を添付：" + "、".join(nm + ".png" for nm, _ in figpages[k]) if k in figpages else "") for k, h in enumerate(heads, 1)]
    return "\n".join(cx), "\n".join(gp)
